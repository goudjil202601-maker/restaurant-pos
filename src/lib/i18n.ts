export type TranslationKey = keyof typeof translations.ar;

export function t(lang: Lang, key: string): string {
  const dict = translations[lang] as Record<string, unknown>;
  const val = dict[key];
  if (typeof val === 'string') return val;
  return key;
}

export function tStatus(lang: Lang, group: 'orderStatus' | 'deliveryStatus', key: string): string {
  const dict = translations[lang] as unknown as Record<string, Record<string, string>>;
  const group2 = dict[group];
  if (group2 && group2[key]) return group2[key];
  return key;
}
